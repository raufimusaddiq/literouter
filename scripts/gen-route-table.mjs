import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, posix, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { Glob } from "bun";

const VERBS = new Set(["GET", "POST", "PUT", "PATCH", "DELETE", "OPTIONS", "HEAD"]);
const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = join(repoRoot, "src/server/routes.js");
const transpiler = new Bun.Transpiler({ loader: "js" });

export function scanApiRoutes(root = "src/app/api") {
  const absRoot = resolve(root);
  const routes = [];
  for (const file of new Glob("**/route.js").scanSync({ cwd: absRoot })) {
    const dir = file.split(/[\\/]/).join("/").replace(/(^|\/)route\.js$/, "");
    const segments = dir ? dir.split("/") : [];
    const methods = transpiler
      .scan(readFileSync(join(absRoot, file), "utf8"))
      .exports.filter((name) => VERBS.has(name))
      .sort();
    let catchAll;
    const pathSegments = segments.map((segment) => {
      const rest = /^\[\.\.\.(.+)\]$/.exec(segment);
      if (rest) {
        catchAll = rest[1];
        return "*";
      }
      const param = /^\[(.+)\]$/.exec(segment);
      return param ? `:${param[1]}` : segment;
    });
    const route = {
      source: ["api", ...segments].join("/"),
      path: "/" + ["api", ...pathSegments].join("/"),
      methods,
    };
    if (catchAll) route.catchAll = catchAll;
    routes.push(route);
  }
  return routes.sort((a, b) => (a.source < b.source ? -1 : a.source > b.source ? 1 : 0));
}

const WILDCARD = "/:path*";

export function expandRewrites(rewrites, routes) {
  const seen = new Set();
  const aliases = [];
  const add = (path, source) => {
    const key = `${path}|${source}`;
    if (seen.has(key)) return;
    seen.add(key);
    aliases.push({ path, source });
  };
  for (const { source: from, destination: to } of rewrites) {
    if (to.endsWith(WILDCARD)) {
      const toPrefix = to.slice(0, -WILDCARD.length);
      const fromPrefix = from.endsWith(WILDCARD) ? from.slice(0, -WILDCARD.length) : from;
      for (const route of routes) {
        if (route.path === toPrefix || route.path.startsWith(toPrefix + "/")) {
          add(fromPrefix + route.path.slice(toPrefix.length), route.source);
        }
      }
      continue;
    }
    for (const route of routes.filter((r) => r.path === to)) {
      if (from.endsWith(WILDCARD)) {
        const fromPrefix = from.slice(0, -WILDCARD.length);
        add(fromPrefix, route.source);
        add(fromPrefix + "/*", route.source);
      } else {
        add(from, route.source);
      }
    }
  }
  return aliases;
}

function buildEntries(routes, rewrites) {
  const bySource = new Map(routes.map((r) => [r.source, r]));
  const entries = routes.map((r) => ({ ...r }));
  for (const alias of expandRewrites(rewrites, routes)) {
    const target = bySource.get(alias.source);
    const entry = { path: alias.path, source: alias.source, methods: target.methods };
    if (target.catchAll && alias.path.endsWith("*")) entry.catchAll = target.catchAll;
    entries.push(entry);
  }
  return entries.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : a.source < b.source ? -1 : 1));
}

export function renderRouteTable(routes, rewrites) {
  const lines = [
    'export const GENERATED = "generated by scripts/gen-route-table.mjs, do not edit";',
    "",
    "export const routeTable = [",
  ];
  for (const entry of buildEntries(routes, rewrites)) {
    const spec = posix.relative("src/server", posix.join("src/app", entry.source, "route.js"));
    const catchAll = entry.catchAll ? `, catchAll: ${JSON.stringify(entry.catchAll)}` : "";
    lines.push(
      `  { path: ${JSON.stringify(entry.path)}, source: ${JSON.stringify(entry.source)}, methods: ${JSON.stringify(entry.methods)}${catchAll}, load: () => import(${JSON.stringify(spec)}) },`,
    );
  }
  lines.push("];", "");
  return lines.join("\n");
}

async function main() {
  const check = process.argv.includes("--check");
  const rewrites = JSON.parse(
    readFileSync(join(repoRoot, "tests/server/fixtures/next-rewrites.json"), "utf8"),
  );
  const next = renderRouteTable(scanApiRoutes(join(repoRoot, "src/app/api")), rewrites);
  if (check) {
    const current = existsSync(outFile) ? readFileSync(outFile, "utf8").replaceAll("\r\n", "\n") : "";
    if (current !== next) {
      console.error("src/server/routes.js is out of date; run: bun run gen:routes");
      process.exit(1);
    }
    return;
  }
  writeFileSync(outFile, next);
  console.log(`wrote ${relative(repoRoot, outFile)}`);
}

if (import.meta.main) await main();
