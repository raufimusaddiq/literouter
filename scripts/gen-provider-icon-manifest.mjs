import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ids = fs
  .readdirSync(path.join(root, "public/providers"))
  .filter((f) => f.endsWith(".png"))
  .map((f) => f.slice(0, -4))
  .sort();
const out = `// AUTO-GENERATED by scripts/gen-provider-icon-manifest.mjs — do not edit.
export const PROVIDER_ICON_IDS = new Set(${JSON.stringify(ids, null, 2)});
`;
fs.writeFileSync(path.join(root, "src/shared/constants/providerIconManifest.js"), out);
