import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

const defaultRoot = resolve(dirname(import.meta.dir));
const MANIFEST_PATH = join("src", "shared", "constants", "providerIconManifest.js");

export function generateProviderIconManifest({ root = defaultRoot } = {}) {
  const ids = readdirSync(join(root, "public", "providers"))
    .filter((file) => file.endsWith(".png"))
    .map((file) => file.slice(0, -4))
    .sort();
  return `// AUTO-GENERATED by scripts/gen-provider-icon-manifest.mjs — do not edit.
export const PROVIDER_ICON_IDS = new Set(${JSON.stringify(ids, null, 2)});
`;
}

export function writeProviderIconManifest({ root = defaultRoot } = {}) {
  const text = generateProviderIconManifest({ root });
  writeFileSync(join(root, MANIFEST_PATH), text);
  return text;
}

if (import.meta.main) writeProviderIconManifest();
